#!/usr/bin/env python3
"""Regenerate the engine-side shader string table from gpu/shaders.

The self-test compiles these at runtime, so the shader text must travel with the
engine. Generating the table from the same files the GPU tests use keeps the two
paths identical instead of relying on a hand copy.
"""

from __future__ import annotations

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHADERS = HERE.parent / "gpu" / "shaders"
OUT = HERE / "hddagi_sparse_shaders.inc"

ENTRIES = [
    ("hddagi_sparse_brick_common.glsl", "SPARSE_COMMON_GLSL", False),
    ("hddagi_sparse_brick_probe.comp", "SPARSE_PROBE_GLSL", True),
    ("hddagi_sparse_brick_canary_write.comp", "SPARSE_CANARY_WRITE_GLSL", True),
    ("hddagi_sparse_brick_canary_check.comp", "SPARSE_CANARY_CHECK_GLSL", True),
    ("hddagi_sparse_brick_manage.comp", "SPARSE_MANAGE_GLSL", True),
]


def main() -> int:
    parts = [
        "// Generated by platform/gen_shader_inc.py. Do not edit by hand.",
        "// The #version line is stripped; the self-test prepends it so it stays first.",
        "",
    ]
    for filename, var, strip_version in ENTRIES:
        body = (SHADERS / filename).read_text()
        if strip_version:
            body = re.sub(r"^#version[^\n]*\n", "", body, flags=re.M)
        parts.append(f'static const char *{var} = R"GLSL(\n{body})GLSL";\n')
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
